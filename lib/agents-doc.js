/**
 * The AGENTS.md scaffolded into a brand-guide directory by `brandkit init`.
 *
 * It is a maintenance contract for AI agents (and humans) working in the host
 * project's brand directory: where the source of truth is, how to read the
 * brand, and (crucially) to record changes in the changelog. It is brand-
 * agnostic (it points at config.json for specifics), so it never goes stale.
 */
function agentsDoc() {
  return [
    '# Working on this brand guide (for AI agents)',
    '',
    'This directory is a **[brandkit](https://github.com/The-Stack-Lab/brandkit) brand guide**.',
    '`config.json` is the single source of truth. It drives the rendered guide (`index.html`) and',
    'the machine-readable exports below.',
    '',
    '## Read the brand from the exports, not the page',
    '',
    '- `brand.json`: full structured brand (colors with roles and contrast, typography, voice, logos, spacing)',
    '- `tokens.json`: W3C design tokens (DTCG `$type`/`$value`) for code and design tooling',
    '- `brand.md`: a brief on how to stay on-brand',
    '',
    'These are regenerated by `brandkit build` / `brandkit export`. If they look stale, rebuild.',
    '',
    '## Two kinds of fields in config.json',
    '',
    'Not every field is yours to hand-write. `brandkit generate` re-derives the measurable ones from',
    "the host project's stylesheets and Tailwind config, and preserves the rest:",
    '',
    '| Field | Owner |',
    '|---|---|',
    '| `theme`, `spacing`, `logoSizes` | **`brandkit generate`**. Overwritten on every run. Fix the source CSS/Tailwind values and re-run; do not hand-edit. |',
    '| `colors`, `fonts` | **Both.** Values (`hex`, `oklch`, `family`) are re-derived every run; your `name`, `role`, `description`, `googleImport` and `fallback` are preserved once written. Swatches are matched on `sourceVar`, so renaming one keeps its prose. |',
    '| `gradients`, `hierarchy`, `cssVariables`, `accessibility`, `typography` | **Derived from `theme`** while they still hold brandkit\'s scaffold. Once you edit them they are yours. |',
    '| `brand`, `voice`, `components`, `sections`, `logos` | **You.** `generate` clears them once (and once only) if they still hold brandkit\'s own placeholder content, so a guide never ships brandkit\'s tagline, voice or marks as this brand\'s. After that they are untouched. |',
    '| `changelog`, `nav` | **You.** `generate` never touches these. |',
    '| `logoUsage`, `formats` | **You.** Optional rules for output that is not a web page: logo clear space, minimum size and misuse, and one entry per canvas (social card, slide, video frame) with its safe zone, logo placement, type styles and backgrounds. Nothing in a codebase can answer these, so `generate` never writes them. |',
    '',
    '### `__TODO` means "not yet defined"',
    '',
    'Any value beginning `__TODO` is a marker, not content. It is deliberately',
    'omitted from `brand.json`, `tokens.json` and `brand.md`, and the guide renders',
    'it as a muted placeholder, so a marker never reaches a client. Two',
    'consequences for you:',
    '',
    '- **Resolve them before the guide is sent.** `brandkit generate` lists them by',
    '  section, and `brandkit build` refuses while an essential one remains',
    '  (`brand`, `voice`, `logos`, `colors`, `fonts`); `--force` builds a draft.',
    '- **Never satisfy one by inventing a value.** These are the fields no',
    '  codebase can answer: a tagline, a voice, why a typeface was chosen. Ask,',
    '  or leave the marker. A plausible guess in a client-approval document is',
    '  the failure this whole contract exists to prevent.',
    '',
    '### `colors` and `theme` are two views of one palette',
    '',
    'They are separate keys and nothing keeps them in sync automatically:',
    '',
    '- `colors` is the **inventory**: the swatch grid the guide documents.',
    '- `theme` is the **rendering**: the CSS custom properties the guide styles *itself* with',
    '  (`--accent`, `--ink`, `--white`, `--gradient-brand`, `--header-bg`, …).',
    '',
    'Setting `colors` alone documents a palette the page never adopts. A fresh scaffold ships',
    "brandkit's own placeholder indigo (`#4F46E5`) in `theme`, so if the guide still renders indigo",
    'chrome while the swatches show the client palette, `theme` was never populated. Run',
    '`brandkit generate`, or map the palette into `theme` by hand if the values are not in the CSS.',
    '',
    '## When you change the brand, record it in the changelog',
    '',
    'Whenever you edit the brand (colors, type, logos, voice, spacing, or anything in `config.json`),',
    'log what changed so the guide keeps an accurate history:',
    '',
    '```bash',
    'npx brandkit changelog "what you changed"   # e.g. "Swapped accent to teal, refreshed the logo"',
    '```',
    '',
    "This prepends an entry to `config.json`'s `changelog` and bumps `brand.version`.",
    '',
    '**Versioning:** a new guide starts at **0.1** and climbs with each change (0.1 → 0.2 → …). When',
    'the brand is finalized, lock it at **1.0**:',
    '',
    '```bash',
    'npx brandkit changelog --lock "Brand finalized"',
    '```',
    '',
    'The changelog renders on its own page (`changelog.html`) and is included in `brand.json` / `brand.md`.',
    '',
    '## Commands',
    '',
    '```bash',
    'npx brandkit generate .     # re-derive theme/colors/fonts/spacing/logos from the project CSS',
    'npx brandkit dev .          # preview at http://localhost:4800 (live reload)',
    'npx brandkit build .        # build static files + exports for deploy',
    'npx brandkit export .       # regenerate brand.json / tokens.json / brand.md',
    'npx brandkit changelog "…"  # record a brand change (see above)',
    '```',
    '',
    '## Rules',
    '',
    '- Edit `config.json`. Do **not** hand-edit `index.html`, `styles.css`, `engine.js`, or',
    '  `changelog.html`. They are universal and overwritten on every rebuild.',
    '- Within `config.json`, respect the ownership table above: change token values at their source',
    '  and re-run `brandkit generate`, rather than typing hex codes into `theme` or `colors`.',
    '- After changing `config.json`: run `brandkit changelog "…"`, then `brandkit build` (or `export`).',
    '- Before calling a guide done, confirm it does not still render the scaffold placeholders:',
    "  indigo accent, `Space Grotesk`/`Inter` type, or brandkit's own logo in the header and sidebar.",
    '  Any of those means a `generate` step was skipped or the source values were never set.',
    ''
  ].join('\n');
}

module.exports = { agentsDoc: agentsDoc };
